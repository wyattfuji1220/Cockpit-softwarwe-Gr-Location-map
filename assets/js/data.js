(function deOverlap() {
  const seen = new Map();
  SITES.forEach(s => {
    const key = s.lat.toFixed(4) + ',' + s.lng.toFixed(4);
    const n = seen.get(key) || 0;
    seen.set(key, n + 1);
    if (n > 0) {
      const angle = (n * 137.5) * Math.PI / 180;   // 黄金角で放射状に配置
      const r = 0.035 * Math.sqrt(n);
      s.lat += r * Math.sin(angle);
      s.lng += r * Math.cos(angle) / Math.max(0.3, Math.cos(s.lat * Math.PI / 180));
    }
  });
})();
